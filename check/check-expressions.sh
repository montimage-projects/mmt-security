#!/usr/bin/env bash
# Checks of the comparisons that compile_rule generates (Montimage fork #31, E1),
# run by `make check`. The test rules check/expressions/*.xml are compiled
# into a temporary rules/ folder (they are not installed) and run on
# check/expressions/expressions.pcap (check/gen/expressions_pcap.py):
#  - 9001-9005 compare two numeric operations, (a - b) OP (c - d): they must
#    compile (a comparison of two operations used to become strcmp) and
#    alert on the right datagram (udp.dest_port 1010, 1050 or 1020, whose
#    dest_port - src_port is 10, 50 and 20, against udp.len - 8 = 20);
#  - 9010-9016 compare http.method with the string 'HEAD': each must alert on
#    the right requests (strcmp: DELETE < GET < HEAD < OPTIONS < POST < PUT),
#    with < and > not inverted;
#  - 9017 compares two string attributes, http.method < http.user_agent: it
#    uses mmt_mem_cmp, which orders by the data size first, then memcmp —
#    so PUT (3) < "AAAA" (4) alerts though strcmp would say >, and
#    DELETE (6) > "a" (1) does not alert though strcmp would say <;
#  - 9020-9026 compare a string with a number: each must be refused by
#    compile_rule with the error of its <!-- expect-error: ... --> marker;
#  - 9027 and 9028 are the presence tests of a string attribute,
#    (ip.src != 0) and (ip.src == 0): they still compile and run.
#
# Usage: check/check-expressions.sh [path/to/compile_rule] [path/to/mmt_sec_standalone]
set -u
cd "$(dirname "$0")/.."
COMPILE_RULE=$(realpath "${1:-./compile_rule}")
STANDALONE=$(realpath "${2:-./mmt_sec_standalone}")
DIR=$PWD/check/expressions
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
status=0
fail(){ echo "  => FAILED: $*"; status=1; }

echo
echo "Testing the comparisons generated by compile_rule"
mkdir "$TMP/rules" "$TMP/out"
for xml in "$DIR"/*.xml; do
	id=$(basename "$xml" .xml)
	exp_err=$(sed -n 's/^<!-- expect-error: \(.*\) -->$/\1/p' "$xml")
	if [ -n "$exp_err" ]; then
		# a rule comparing a string with a number: it must be refused, with the error
		if "$COMPILE_RULE" "$TMP/rules/$id.so" "$xml" > "$TMP/$id.log" 2>&1; then
			fail "rule $id compiles but must be refused (a string with a number)"
		elif ! grep -qF "$exp_err" "$TMP/$id.log"; then
			fail "rule $id is refused but without \"$exp_err\""
			grep -E "error|Error|HALT" "$TMP/$id.log" | head -5 | sed 's/^/    | /'
		fi
	elif ! "$COMPILE_RULE" "$TMP/rules/$id.so" "$xml" > "$TMP/$id.log" 2>&1; then
		fail "rule $id does not compile"
		grep -E "error|strcmp" "$TMP/$id.log" | head -5 | sed 's/^/    | /'
	fi
done
# the standalone loads every .so of ./rules
( cd "$TMP" && "$STANDALONE" -t "$DIR/expressions.pcap" -f "$TMP/out/" > "$TMP/run.log" 2>&1 ) \
	|| { cat "$TMP/run.log"; fail "mmt_sec_standalone failed"; }

# rule -> the value of its event_1 attribute (udp.dest_port or http.method) in each alert
got(){ # rule
	cat "$TMP"/out/*.csv 2>/dev/null | awk -F, -v r="$1" '$5 == r' \
		| grep -oE '"event_1":\{[^}]*' | grep -oE '\["(udp\.dest_port|http\.method)",("[A-Z]*"|[0-9]*)\]' \
		| sed -E 's/.*,"?([A-Z0-9]*)"?\]/\1/' | sort | paste -sd " "
}
# rule  expected values (sorted, - for no alert)
while read -r rule expected; do
	[ "$expected" = - ] && expected=
	g=$(got "$rule")
	printf "  rule %s: %-14s %s\n" "$rule" "${g:-(none)}" "$(sed -n 's/^<!-- Test rule of [^:]*: \(.*\) -->$/\1/p' "$DIR/$rule.xml")"
	[ "$g" = "$expected" ] || fail "rule $rule alerts on [${g}], expected [${expected}]"
done <<'EXPECT'
9001 1010
9002 1050
9003 1020
9004 1010 1020
9005 1010 1050
9010 DELETE GET
9011 OPTIONS POST PUT
9012 HEAD
9013 DELETE GET OPTIONS POST PUT
9014 DELETE GET HEAD
9015 HEAD OPTIONS POST PUT
9016 OPTIONS POST PUT
9017 GET HEAD OPTIONS POST PUT
9027 GET
9028 -
EXPECT
[ $status -eq 0 ] && echo "  => OK"
exit $status
