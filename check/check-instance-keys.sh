#!/usr/bin/env bash
# Instance keys of the generated rules (fork #51, PR #55 review finding 3),
# run by `make check`. compile_rule must not key an event whose expression
# calls an embedded function before an equality `att == att.N` of its key
# (purity invariant, gen_code.c _collect_instance_key_pairs): the engine
# skips the guard of instances of another key, and such a guard would have
# called the function on those visits. Each check/instance_keys/*.xml has
# an `expect-keyed:` marker, the events that must get an
# instance_key_cmp_<rule>_<event> array ("none" for none); an event left
# out must also be named by compile_rule's note.
#
# Usage: check/check-instance-keys.sh [path/to/compile_rule]
set -u
cd "$(dirname "$0")/.."
COMPILE_RULE=$(realpath "${1:-./compile_rule}")
DIR=$PWD/check/instance_keys
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
status=0
fail(){ echo "  => FAILED: $*"; status=1; }

echo
echo "Testing the instance keys generated by compile_rule"
for xml in "$DIR"/*.xml; do
	id=$(basename "$xml" .xml)
	want=$(sed -n 's/^ *expect-keyed: \([0-9 ]*\|none\) -->$/\1/p' "$xml")
	[ -n "$want" ] || { fail "$id: no expect-keyed marker"; continue; }
	[ "$want" = none ] && want=
	if ! "$COMPILE_RULE" "$TMP/$id.c" "$xml" -c > "$TMP/$id.log" 2>&1; then
		tail -5 "$TMP/$id.log" | sed 's/^/    | /'
		fail "$id: compile_rule -c failed"
		continue
	fi
	got=$(grep -o "instance_key_cmp_${id}_[0-9]*\[\]" "$TMP/$id.c" | sed 's/.*_\([0-9]*\)\[\]/\1/' | sort -n | paste -sd' ')
	[ "$got" = "$want" ] || fail "$id: keyed events '$got', expected '$want'"
	# every event of the rule that has an equality but is not keyed is named by the note
	for ev in $(grep -o 'event_id="[0-9]*"' "$xml" | grep -o '[0-9]*'); do
		case " $want " in *" $ev "*) continue ;; esac
		grep -q "== ip\.[a-z]*\.[0-9]" <(sed -n "/event_id=\"$ev\"/,/\/>/p" "$xml") || continue
		grep -q "Rule $id, event $ev: not indexed by instance key" "$TMP/$id.log" \
			|| fail "$id: no note for event $ev"
	done
	[ $status -eq 0 ] && echo "  rule $id: keyed events '${got:-none}'"
done
[ $status -eq 0 ] && echo "  => OK"
exit $status
